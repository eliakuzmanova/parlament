export function stageOf(title) {
  const t = (title || "").toLowerCase();
  const parts = [];
  if (/първо (гласуване|четене)/.test(t)) parts.push("Първо четене");
  else if (/второ (гласуване|четене)/.test(t)) parts.push("Второ четене");
  else if (/вето|повторно обсъждане/.test(t)) parts.push("Повторно гласуване след вето");
  else if (/(чл\.|§|параграф|предложение на|предложението на)/.test(t)) parts.push("По текст");
  if (/прегласуване/.test(t)) parts.push("прегласуване");
  return parts.join(", ");
}

const djb2 = (s) => {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return h.toString(36);
};

// Към кой законопроект / решение принадлежи гласуването.
// 1) номер на акта (52-554-01-114), ако го има в заглавието;
// 2) иначе „Законопроект за …“ / „Проект за решение …“ до първата запетая;
// 3) иначе цялото заглавие.
export function billOf(title) {
  const t = (title || "").replace(/\s+/g, " ").trim();
  const num = t.match(/№\s*(\d{2,3}-\d{3}-\d{2}-\d+)/);
  const m = t.match(
    /((?:законопроект|проект(?:о)? (?:на|за) решение|проекторешение|закон|решение|декларация)\s+(?:за|на|относно)\s+[^,;№(]+)/i,
  );
  let label = m ? m[1] : t;
  label = label
    .replace(/[-–—]?\s*(прегласуване|първо гласуване|второ гласуване|на първо четене|на второ четене)/gi, "")
    .replace(/[\s,.;:–—-]+$/u, "")
    .trim();
  if (label.length > 220) label = label.slice(0, 217) + "…";
  label = label.charAt(0).toUpperCase() + label.slice(1);
  const key = num ? num[1] : "b" + djb2(label.toLowerCase());
  return { key, label, number: num ? num[1] : null };
}

// Резултат. Изчислява се от поименните данни, затова при специални мнозинства
// приложението пише изрично какво мнозинство се изисква.
//   обикновено: „за“ > половината от гласувалите
//   след вето:  „за“ ≥ 121 (повече от половината от всички депутати)
//   конституция: изисква квалифицирано мнозинство – не изчисляваме
export function resultOf(title, y, n, a) {
  const t = (title || "").toLowerCase();
  if (/конституц/.test(t) && /(изменение|допълнение|промени)/.test(t) && !/процедур/.test(t)) {
    return { res: "q", note: "Изисква квалифицирано мнозинство" };
  }
  if (/вето|повторно обсъждане/.test(t)) {
    return { res: y >= 121 ? "pass" : "fail", note: "Нужни са поне 121 гласа „за“" };
  }
  const cast = y + n + a;
  return { res: y > cast / 2 ? "pass" : "fail", note: "" };
}
